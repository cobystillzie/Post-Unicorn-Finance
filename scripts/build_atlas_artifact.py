# ---- chart 2: liquidity horizons (vertical bars on a time axis) ----
def horizon_bucket(r):
    s = (r.get('horizon_years') or '').strip().lower()
    if s in ('decades', 'permanent', 'forever'):
        return 'No exit'
    nums = [float(x) for x in re.findall(r'\d+\.?\d*', s)]
    if nums:
        m = sum(nums) / len(nums)
        if m <= 2: return '≤2y'
        if m <= 3: return '2–3y'
        if m <= 5: return '3–5y'
        if m < 6: return '5–6y'
        if m <= 9.5: return '6–9y'
        return '10y+'
    if r['asset_class'] == 'Permanent' or (r.get('liquidity_band') or '') == 'Permanent':
        return 'No exit'
    return 'Not stated'

H_BUCKETS = ['≤2y', '2–3y', '3–5y', '5–6y', '6–9y', '10y+', 'No exit', 'Not stated']
H_COLORS = {'≤2y': '#1b5e20', '2–3y': '#2e7d32', '3–5y': '#43932f', '5–6y': '#6aa84f',
            '6–9y': '#b7791f', '10y+': '#8a5a1a', 'No exit': '#37568c', 'Not stated': '#9aa39d'}

def chart_horizons():
    bc = Counter(horizon_bucket(r) for r in rows)
    max_n = max(bc.get(b, 0) for b in H_BUCKETS)
    w, h, plot_h, base = 640, 235, 160, 190
    slot = w / len(H_BUCKETS)
    out = [svg_open(w, h, 'Distribution of stated liquidity horizons')]
    out.append('<line x1="0" y1="%d" x2="%d" y2="%d" stroke="#dde2da" stroke-width="1"/>' % (base, w, base))
    for i, b in enumerate(H_BUCKETS):
        n = bc.get(b, 0)
        x = i * slot + slot / 2
        bh = max(3, n / max_n * plot_h) if n else 0
        if n:
            out.append('<rect x="%g" y="%g" width="44" height="%g" rx="2" fill="%s"><title>%s: %d funds</title></rect>'
                       % (x - 22, base - bh, bh, H_COLORS[b], esc(b), n))
            out.append(txt(x, base - bh - 7, n, size=12.5, fill=INK, anchor='middle', weight='600'))
        out.append(txt(x, base + 17, b, anchor='middle'))
    out.append(txt(0, h - 3, 'faster capital return → longer hold', size=10.5))
    out.append('</svg>')
    return ''.join(out)

