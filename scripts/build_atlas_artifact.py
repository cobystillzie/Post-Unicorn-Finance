def svg_open(w, h, label):
    return ('<svg viewBox="0 0 %d %d" role="img" aria-label="%s" '
            'style="width:100%%;height:auto;max-width:%dpx;display:block">' % (w, h, esc(label), w))

def txt(x, y, s, size=11, fill=MUTED, anchor='start', weight='400', fam=MONO):
    return ('<text x="%g" y="%g" font-family="%s" font-size="%g" fill="%s" '
            'text-anchor="%s" font-weight="%s">%s</text>' % (x, y, fam, size, fill, anchor, weight, esc(str(s))))

