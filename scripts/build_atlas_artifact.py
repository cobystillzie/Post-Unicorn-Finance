def chart_countries():
    by_country = defaultdict(Counter)
    for r in rows:
        c = (r.get('country') or 'Unknown').strip() or 'Unknown'
        by_country[c][r['asset_class']] += 1
    ordered = sorted(by_country.items(), key=lambda kv: (-sum(kv[1].values()), kv[0]))
    row_h, label_w, bar_w = 23, 158, 400
    max_n = sum(ordered[0][1].values())
    w, h = 660, len(ordered) * row_h + 10
    out = [svg_open(w, h, 'Number of funds per country, split by asset class')]
    for i, (c, cc) in enumerate(ordered):
        y = i * row_h + 6
        total = sum(cc.values())
        label = c if c != 'Unknown' else 'Not stated / remote'
        out.append(txt(label_w - 8, y + 11, label, anchor='end', fill=INK, fam='system-ui,sans-serif'))
        x = float(label_w)
        for k in CLASS_ORDER:
            n = cc.get(k, 0)
            if not n: continue
            seg = max(2.0, n / max_n * bar_w)
            out.append('<rect x="%g" y="%g" width="%g" height="14" fill="%s"><title>%s — %s: %d</title></rect>'
                       % (x, y, seg - 1, CLASS_ORDER[k][1], esc(label), esc(k), n))
            x += seg
        out.append(txt(x + 7, y + 11, total, fill=MUTED))
    out.append('</svg>')
    return ''.join(out), len(ordered)

