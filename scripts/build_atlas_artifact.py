NE_OF_ATLAS = {'United States': 'United States of America'}  # every other atlas name matches NE ADMIN
ATLAS_OF_NE = {v: k for k, v in NE_OF_ATLAS.items()}
MAP_BASE = '#e6eae5'          # countries with no funds
MAP_STROKE = '#cfd6cd'
MAP_BANDS = [(1, '#cfe0dd', '1'), (4, '#9ec6c0', '2–4'), (10, '#66a49a', '5–10'),
             (30, '#2f7d72', '11–30'), (10 ** 9, '#0f5257', '30+')]

def map_fill(n):
    if n <= 0:
        return MAP_BASE
    for hi, col, _ in MAP_BANDS:
        if n <= hi:
            return col
    return MAP_BANDS[-1][1]

def _map_country(ne_name, geo, n):
    atlas = ATLAS_OF_NE.get(ne_name, ne_name)
    fill = map_fill(n)
    common = 'fill="%s" stroke="%s" stroke-width="0.4"' % (fill, MAP_STROKE)
    if n:
        title = '<title>%s — %d fund%s (click to filter)</title>' % (esc(atlas), n, '' if n == 1 else 's')
        attrs = ('class="mc" data-country="%s" tabindex="0" role="button" aria-label="%s, %d funds" %s'
                 % (esc(atlas), esc(atlas), n, common))
    else:
        title, attrs = '', 'class="mc0" %s' % common
    if geo['d']:
        return '<path d="%s" fill-rule="evenodd" %s>%s</path>' % (geo['d'], attrs, title)
    return '<circle cx="%g" cy="%g" r="3.2" %s>%s</circle>' % (geo['cx'], geo['cy'], attrs, title)

def chart_worldmap():
    map_counts = Counter()
    for r in rows:
        c = (r.get('country') or '').strip()
        if c and c != 'Unknown':
            map_counts[c] += 1
    unknown_n = sum(1 for r in rows if (r.get('country') or 'Unknown').strip() in ('', 'Unknown'))
    vb = MAP_DATA['viewBox']
    entries = [(ne, geo, map_counts.get(ATLAS_OF_NE.get(ne, ne), 0))
               for ne, geo in MAP_DATA['countries'].items()]
    # zero-fund countries first (background layer), shaded countries painted on top
    ordered = [e for e in entries if not e[2]] + [e for e in entries if e[2]]
    body = ''.join(_map_country(ne, geo, n) for ne, geo, n in ordered)
    svg = ('<svg viewBox="0 0 %g %g" role="img" aria-label="World map of funds by country" '
           'class="worldmap" xmlns="http://www.w3.org/2000/svg">%s</svg>' % (vb[2], vb[3], body))
    legend = '<span class="mlg"><i style="background:%s;border:1px solid %s"></i>none</span>' % (MAP_BASE, MAP_STROKE)
    legend += ''.join('<span class="mlg"><i style="background:%s"></i>%s</span>' % (col, lab)
                      for _, col, lab in MAP_BANDS)
    return svg, legend, unknown_n, len(map_counts)

